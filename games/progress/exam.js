  function generate(seed) {
    const random = () => {
      seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
      return seed / 4294967296;
    };
    return [...groups, essays].map((pool) => {
      const item = pool[Math.floor(random() * pool.length)];
      const order = item.options.map((_, index) => index);
      for (let index = order.length - 1; index > 0; index--) {
        const other = Math.floor(random() * (index + 1));
        [order[index], order[other]] = [order[other], order[index]];
      }
      return { id: item.id, order };
    });
  }
  function valid(questions) {
    return Array.isArray(questions) && questions.length === 7 &&
      questions.every((item, index) => item && [...groups, essays][index].some((q) => q.id === item.id) &&
        Array.isArray(item.order) && item.order.length === 4 && new Set(item.order).size === 4 &&
        item.order.every((n) => Number.isInteger(n) && n >= 0 && n < 4));
  }
  function grade(questions, answers) {
    if (!valid(questions) || answers.length !== questions.length ||
      answers.some((n) => !Number.isInteger(n) || n < 0 || n >= 4)) return null;
    const marked = questions.map((item, index) => {
      const q = catalog.get(item.id);
      return { kind: q.kind, prompt: q.prompt, selected: q.options[item.order[answers[index]]],
        best: q.options[q.points.indexOf(Math.max(...q.points))], explanation: q.explanation,
        points: q.points[item.order[answers[index]]], max: Math.max(...q.points) };
    });
    return { score: marked.reduce((sum, item) => sum + item.points, 0), marked };
  }
  function display(item) {
    const q = catalog.get(item.id);
    return { kind: q.kind, prompt: q.prompt, options: item.order.map((n) => q.options[n]) };
  }
  return { generate, grade, valid, display };
